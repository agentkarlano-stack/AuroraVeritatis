import { MACRO_SERIES, type MacroResponse } from '../../../shared/macro';
import type { Provenance } from '../../../shared/types';
import { INSTRUMENTS, INSTRUMENT_MAP } from '../../data/instruments';
import { demoBars, type Bar } from '../demoMarket';
import type { IntervalId } from './intervals';

/** A price history the chart editor can show, with everything the info bar has to disclose about it. */
export interface Dataset {
  symbol: string;
  name: string;
  provider: string;
  licence: string;
  provenance: Provenance;
  /** Live, delayed, end of day or simulated. */
  status: string;
  assetType: string;
  currency: string;
  timezone: string;
  baseInterval: IntervalId;
  hasOhlc: boolean;
  hasVolume: boolean;
  decimals: number;
  bars: Bar[];
}

export interface InstrumentOption {
  symbol: string;
  name: string;
  group: 'ECB reference rates (official)' | 'Simulated demo instruments';
  provenance: Provenance;
}

const ECB_PREFIX = 'ECB:';
const ECB_FX = MACRO_SERIES.filter((s) => s.group === 'fx');

export const INSTRUMENT_OPTIONS: InstrumentOption[] = [
  ...ECB_FX.map((s) => ({ symbol: `${ECB_PREFIX}${s.id}`, name: `EUR/${s.id.slice(3)}: euro in ${s.label}`, group: 'ECB reference rates (official)' as const, provenance: 'confirmed' as const })),
  ...INSTRUMENTS.map((i) => ({ symbol: i.symbol, name: i.name, group: 'Simulated demo instruments' as const, provenance: 'simulated' as const })),
];

export const isKnownSymbol = (s: string) => INSTRUMENT_MAP.has(s) || ECB_FX.some((x) => `${ECB_PREFIX}${x.id}` === s);
export const isEcbSymbol = (s: string) => s.startsWith(ECB_PREFIX);
/** API path for symbols loaded from the Worker, or null for symbols available in the browser. */
export const remotePath = (s: string) => (isEcbSymbol(s) ? `/api/macro/${s.slice(ECB_PREFIX.length)}?years=25` : null);

export function demoDataset(symbol: string): Dataset | null {
  const inst = INSTRUMENT_MAP.get(symbol);
  if (!inst) return null;
  return {
    symbol,
    name: inst.name,
    provider: 'Aurora demo model (seeded random walk)',
    licence: 'Generated by Aurora; not market data',
    provenance: 'simulated',
    status: 'Simulated',
    assetType: inst.assetClass.replace('-', ' '),
    currency: inst.assetClass === 'fx' ? 'Quote currency' : 'Index points',
    timezone: 'UTC',
    baseInterval: '1D',
    hasOhlc: true,
    hasVolume: true,
    decimals: inst.decimals,
    bars: demoBars(symbol),
  };
}

/**
 * ECB euro reference rates: one official value per TARGET working day (around 16:00 CET). Closing values only: no
 * open, high, low or volume are published, so those are never invented. Bars carry the rate as O = H = L = C, and the
 * dataset is flagged close-only so candle types and range-based indicators are disabled.
 */
export function ecbDataset(symbol: string, res: MacroResponse): Dataset | null {
  const id = symbol.slice(ECB_PREFIX.length);
  const def = ECB_FX.find((s) => s.id === id);
  const obs = res.series.find((s) => s.id === id)?.obs ?? [];
  if (!def || !obs.length) return null;
  return {
    symbol,
    name: `EUR/${id.slice(3)} (${def.label} per euro)`,
    provider: 'European Central Bank, euro foreign exchange reference rates',
    licence: 'Source: ECB statistics. Reuse permitted with attribution',
    provenance: 'confirmed',
    status: 'End of day (official reference rate)',
    assetType: 'FX reference rate',
    currency: id.slice(3),
    timezone: 'CET (published around 16:00)',
    baseInterval: '1D',
    hasOhlc: false,
    hasVolume: false,
    decimals: Math.abs(obs.at(-1)!.value) >= 100 ? 2 : 4,
    bars: obs.map((o) => ({ time: o.date, open: o.value, high: o.value, low: o.value, close: o.value, volume: 0 })),
  };
}
